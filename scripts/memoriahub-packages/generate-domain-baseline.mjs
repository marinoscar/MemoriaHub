#!/usr/bin/env node
// Generates the text of the memoriahub-db baseline migration (RETRO-J3, #606) from a database that
// ran the web app's whole migration history: the domain's enums, functions and tables, with their
// constraints, indexes, triggers and row-level-security policies, in dependency order, as
// `pg_dump --schema-only` prints them. A one-off provenance tool: the baseline it wrote is immutable
// (its sha256 is in packages/memoriahub-db/migrations/manifest.json), so this runs again only to
// re-derive the file for review.
//
// Usage: PGHOST=... PGUSER=... PGPASSWORD=... node scripts/memoriahub-packages/generate-domain-baseline.mjs <database> [out.sql]
//   PGPASSWORD is read from the environment by psql and pg_dump; no credential is written anywhere.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const database = process.argv[2];
const out = process.argv[3];
if (!database) {
  console.error('usage: generate-domain-baseline.mjs <database> [out.sql]');
  process.exit(2);
}

/** The tables the domain owns: every `@@map` of packages/memoriahub-db/schema/memoriahub.*.prisma. */
function domainTables() {
  const dir = join(here, '..', '..', 'packages', 'memoriahub-db', 'schema');
  const names = new Set();
  for (const file of execFileSync('ls', [dir], { encoding: 'utf8' }).split('\n').filter(Boolean)) {
    for (const m of readFileSync(join(dir, file), 'utf8').matchAll(/@@map\("([a-z_]+)"\)/g)) names.add(m[1]);
  }
  // media_visual_embedding exists only in migration SQL (Prisma cannot model its vector(512) column).
  names.add('media_visual_embedding');
  return [...names].sort();
}

const psql = (sql) => execFileSync('psql', ['-X', '-A', '-t', '-d', database, '-c', sql], { encoding: 'utf8' }).trim();
const tables = domainTables();
const list = tables.map((t) => `'${t}'`).join(',');

const enums = psql(
  `SELECT 'CREATE TYPE public."' || t.typname || '" AS ENUM (' || string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) || E');\n'
   FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
   WHERE t.typtype = 'e' AND t.typnamespace = 'public'::regnamespace AND t.typname IN (
     SELECT DISTINCT c.udt_name FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name IN (${list}))
   GROUP BY t.typname ORDER BY t.typname`,
);
const fnNames = ['mh_default_org_id', 'face_embedding_to_vector', 'faces_sync_embedding_vec', 'mh_content_owner_from_scope'];
const functions = fnNames
  .map((n) => psql(`SELECT pg_get_functiondef(p.oid) || ';' FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.proname = '${n}'`))
  .join('\n\n');
const dump = execFileSync(
  'pg_dump',
  ['-s', '--no-owner', '--no-privileges', '--no-comments', ...tables.flatMap((t) => ['-t', `public.${t}`]), database],
  { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
)
  .split('\n')
  .filter((line) => !/^SET /.test(line) && !/^SELECT pg_catalog\.set_config/.test(line) && !/^-- (Dumped|PostgreSQL)/.test(line) && !/^\\(un)?restrict /.test(line))
  .join('\n')
  .replace(/\n{3,}/g, '\n\n')
  .trim();

const text = `-- memoriahub-db baseline (RETRO-J3, #606): the whole MemoriaHub domain schema in its final state.
--
-- For a host with no MemoriaHub migration history. A host that already ran the web app's history
-- (it holds prisma/migrations/20260610000000_add_media_domain) adopts this file without running it:
-- \`memoriahub-db sync\` records it in prisma/memoriahub.lock and writes nothing.
--
-- Requires the platform schema first (users, organizations with is_default, groups, storage_objects,
-- worker_nodes, personal_access_tokens) and the \`vector\` extension (never created here).
-- Generated by scripts/memoriahub-packages/generate-domain-baseline.mjs from a database migrated with
-- the web app's history; verified equal to it by packages/memoriahub-db/test/apply.db.test.ts.

-- Enums
${enums}

-- Functions
${functions}

-- Tables, constraints, indexes, triggers and row-level security
${dump}
`;
if (out) writeFileSync(out, text);
else process.stdout.write(text);
