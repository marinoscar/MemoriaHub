/**
 * Short-lived admin connections to the Postgres CLUSTER (issue #344, epic #339).
 *
 * WHY THIS EXISTS AT ALL, and why it cannot be Prisma:
 *
 * The restore swap renames the live database. `ALTER DATABASE … RENAME TO …`
 * fails while ANY session is connected to the database being renamed, and a
 * session cannot rename the database it is itself connected to. So the rename
 * — and the `CREATE DATABASE`/`DROP DATABASE`/`pg_terminate_backend` around it
 * — must run over a connection to a DIFFERENT database in the same cluster,
 * conventionally the `postgres` maintenance database.
 *
 * Prisma's client is bound to one datasource URL and holds a POOL. Both facts
 * disqualify it here: the pool is precisely the set of connections that has to
 * be gone before the rename can succeed, and `CREATE DATABASE` cannot run
 * inside the implicit transaction Prisma wraps some paths in. A raw `pg.Client`
 * — one connection, opened for a handful of statements and closed immediately —
 * is the right tool, and keeping it OUT of the Prisma pool is the point rather
 * than an incidental detail.
 *
 * IDENTIFIER SAFETY: every database name reaching a statement here goes through
 * {@link quoteIdentifier}, which validates against a strict allowlist BEFORE
 * quoting. Database names cannot be passed as bind parameters in DDL, so the
 * usual parameterised-query defence is unavailable; the allowlist is what
 * stands in for it. Names are generated server-side (`memoriahub_restore_<ts>`)
 * and never taken from a request body, so this is defence in depth — but a
 * future caller passing a name through must still be safe.
 */

import { Client } from 'pg';

import type { PgConnectionConfig } from './pg-dump.util';

/** The maintenance database renames are issued from. Overridable for odd clusters. */
export function resolveMaintenanceDatabase(
  envValue: string | undefined = process.env.PG_MAINTENANCE_DB,
): string {
  const trimmed = (envValue ?? '').trim();
  return trimmed || 'postgres';
}

// ---------------------------------------------------------------------------
// Client factory seam (test-only)
// ---------------------------------------------------------------------------

/** The narrow slice of `pg.Client` this module uses. */
export interface AdminClientLike {
  connect(): Promise<void>;
  query<T = any>(text: string, values?: unknown[]): Promise<{ rows: T[] }>;
  end(): Promise<void>;
}

export interface AdminClientConfig {
  host: string;
  port: number;
  user: string;
  password: string;
  database: string;
  connectionTimeoutMillis?: number;
  statement_timeout?: number;
}

export type AdminClientFactory = (cfg: AdminClientConfig) => AdminClientLike;

const realFactory: AdminClientFactory = (cfg) =>
  new Client(cfg) as unknown as AdminClientLike;

let clientFactory: AdminClientFactory = realFactory;

/**
 * TEST-ONLY seam mirroring `pg-dump.util.ts`'s `__setSpawnForTests`. Pass `null`
 * to restore the real `pg.Client`. Production code must never call this.
 *
 * The restore state machine is unit-tested with this factory and `spawn` both
 * mocked, which is what makes it testable at all in an environment with no
 * Postgres — see `database-restore.service.spec.ts`.
 */
export function __setAdminClientFactoryForTests(
  factory: AdminClientFactory | null,
): void {
  clientFactory = factory ?? realFactory;
}

// ---------------------------------------------------------------------------
// Identifier quoting
// ---------------------------------------------------------------------------

/** Postgres identifiers are capped at 63 bytes; longer names are silently truncated. */
export const MAX_IDENTIFIER_LENGTH = 63;

const SAFE_IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;

/**
 * Validate and double-quote a database identifier for interpolation into DDL.
 *
 * Rejects anything outside `[A-Za-z_][A-Za-z0-9_]*` rather than escaping it:
 * a legal-but-exotic name (embedded quotes, spaces, unicode) has no business
 * being generated by this feature, so refusing is both safer and a clearer
 * signal that something upstream is wrong.
 */
export function quoteIdentifier(name: string): string {
  if (!name || !SAFE_IDENTIFIER.test(name)) {
    throw new Error(`Unsafe database identifier: ${JSON.stringify(name)}`);
  }
  if (name.length > MAX_IDENTIFIER_LENGTH) {
    throw new Error(
      `Database identifier exceeds ${MAX_IDENTIFIER_LENGTH} bytes: ${name}`,
    );
  }
  return `"${name}"`;
}

// ---------------------------------------------------------------------------
// Connection helper
// ---------------------------------------------------------------------------

export interface AdminConnectionOptions {
  /** Database to connect to. Defaults to the maintenance database. */
  database?: string;
  connectTimeoutMs?: number;
  /**
   * Per-statement timeout. Deliberately UNSET (0 = no limit) by default: the
   * one long statement here is `CREATE DATABASE`, and a timeout that fires
   * mid-DDL buys nothing but ambiguity about whether it landed.
   */
  statementTimeoutMs?: number;
}

const DEFAULT_CONNECT_TIMEOUT_MS = 10_000;

/**
 * Open a single connection, run `fn`, and ALWAYS close it.
 *
 * The `finally` is load-bearing rather than hygiene: a leaked connection to the
 * live database is exactly what makes the subsequent `ALTER DATABASE … RENAME`
 * fail, so the one thing this helper must never do is outlive its caller.
 */
export async function withAdminConnection<T>(
  cfg: PgConnectionConfig,
  fn: (client: AdminClientLike) => Promise<T>,
  opts: AdminConnectionOptions = {},
): Promise<T> {
  const client = clientFactory({
    host: cfg.host,
    port: cfg.port,
    user: cfg.user,
    password: cfg.password,
    database: opts.database ?? resolveMaintenanceDatabase(),
    connectionTimeoutMillis: opts.connectTimeoutMs ?? DEFAULT_CONNECT_TIMEOUT_MS,
    statement_timeout: opts.statementTimeoutMs ?? 0,
  });

  await client.connect();
  try {
    return await fn(client);
  } finally {
    try {
      await client.end();
    } catch {
      // A close failure cannot be acted on and must not mask the real result.
    }
  }
}

