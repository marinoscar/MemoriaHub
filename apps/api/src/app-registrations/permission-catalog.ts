// =============================================================================
// The seed's view of the role and permission registries, as a committed file
// (RETRO-B2, issue #611)
// =============================================================================
//
// The catalog is `buildPermissionCatalog()` of `@marinoscar/platform-api/core`
// after `permission-manifest.ts` filled the registries. This file renders it the
// way the app commits it: the generator (`scripts/generate-permission-catalog.ts`,
// `npm run catalog:permissions --workspace=api`) writes it to
// `prisma/catalog/permissions.json`, which `prisma/seed.ts` reads (the production
// image carries `prisma/` but no `src/`), and
// `test/prisma/permission-catalog.spec.ts` fails when the committed JSON no longer
// equals what the registries render. It replaces `rbac.catalog.ts` and the boot-time
// RBAC reconcile: a permission is added by declaring it, regenerating, and seeding.

import { buildPermissionCatalog, type PermissionCatalog } from '@marinoscar/platform-api/core';

import './permission-manifest';

/** The command that regenerates `prisma/catalog/permissions.json`. */
export const PERMISSION_CATALOG_COMMAND = 'npm run catalog:permissions --workspace=api';

/** The committed catalog file, relative to `apps/api`. */
export const PERMISSION_CATALOG_PATH = 'prisma/catalog/permissions.json';

/** The catalog exactly as the committed file holds it (2-space JSON, trailing newline). */
export function renderPermissionCatalog(catalog: PermissionCatalog = buildPermissionCatalog()): string {
  const document = { $comment: `Generated by ${PERMISSION_CATALOG_COMMAND}. Do not edit.`, ...catalog };
  return `${JSON.stringify(document, null, 2)}\n`;
}

/** `null` when the committed file is current, otherwise the failure message. */
export function checkPermissionCatalog(committed: string | undefined): string | null {
  if (committed === renderPermissionCatalog()) return null;
  return (
    `${PERMISSION_CATALOG_PATH} is ${committed === undefined ? 'missing' : 'stale'}: ` +
    `run ${PERMISSION_CATALOG_COMMAND} and commit the result.`
  );
}
