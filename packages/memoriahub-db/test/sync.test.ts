import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import {
  MemoriahubLockError,
  MemoriahubSyncError,
  afterHostNames,
  applyMemoriahubSync,
  checkMemoriahubInstall,
  findMissingHostModels,
  planMemoriahubSync,
  readInventories,
  readManifest,
  sha256Hex,
  stableName,
  type MemoriahubSyncOptions,
} from '../src/index.js';
import { PACKAGE_DIR, cleanup, freshHost, freshPackage } from './helpers.js';

afterEach(cleanup);

const manifest = readManifest(join(PACKAGE_DIR, 'migrations'));
const baseline = manifest.migrations[0]!;
const HISTORY_MARKER = baseline.baseline!.adoptedWhenHostHas;

function sync(root: string, options: Partial<MemoriahubSyncOptions> = {}) {
  const plan = planMemoriahubSync({ root, platformSchemaDir: null, ...options });
  applyMemoriahubSync(plan);
  return plan;
}

const migrationDirs = (root: string) => readdirSync(join(root, 'prisma', 'migrations')).sort();
const lockOf = (root: string) => JSON.parse(readFileSync(join(root, 'prisma', 'memoriahub.lock'), 'utf8'));

/** A host that ran the web app's history: it holds the migration the baseline is adopted by. */
function historyHost(): string {
  const root = freshHost();
  const dir = join(root, 'prisma', 'migrations', HISTORY_MARKER);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'migration.sql'), '-- the web app history (fixture)\n');
  return root;
}

/** A private copy of the package with one more migration after the baseline. */
function packageWithExtra(): { packageDir: string; id: string; sql: string } {
  const packageDir = freshPackage();
  const id = '20270401090000_add_probe';
  const sql = 'ALTER TABLE "media_items" ADD COLUMN "probe" TEXT;\n';
  mkdirSync(join(packageDir, 'migrations', id), { recursive: true });
  writeFileSync(join(packageDir, 'migrations', id, 'migration.sql'), sql);
  const file = join(packageDir, 'migrations', 'manifest.json');
  const document = JSON.parse(readFileSync(file, 'utf8'));
  document.migrations.push({ id, slice: 'media', sha256: sha256Hex(Buffer.from(sql)), requiresHostTables: ['users'] });
  writeFileSync(file, `${JSON.stringify(document, null, 2)}\n`);
  return { packageDir, id, sql };
}

describe('afterHostNames', () => {
  it('numbers one second after the newest directory, one second apart', () => {
    expect(afterHostNames(['20260914130000_add_a', '20260914140000_add_b'], ['20270102000000_x', '20260101000000_y'])).toEqual([
      '20270102000001_memoriahub_add_a',
      '20270102000002_memoriahub_add_b',
    ]);
  });
});

describe('stableName', () => {
  it('inserts memoriahub_ after the id timestamp', () => {
    expect(stableName('20261110200000_domain_baseline')).toBe('20261110200000_memoriahub_domain_baseline');
    expect(stableName('20270401090000_add_probe')).toBe('20270401090000_memoriahub_add_probe');
  });

  it('refuses an id without a 14-digit timestamp prefix', () => {
    expect(() => stableName('add_probe')).toThrow(MemoriahubSyncError);
  });
});

describe('sync into a host with the web app history (the web app case)', () => {
  it('adopts the baseline: no migration directory is written, the lock records it, fragments are installed', async () => {
    const root = historyHost();
    const before = migrationDirs(root);
    const plan = sync(root);
    expect(plan.installs.map((i) => i.action)).toEqual(['adopt-baseline']);
    expect(migrationDirs(root)).toEqual(before);

    const lock = lockOf(root);
    expect(lock.migrations).toEqual([{ adopted: true, installedDir: null, originId: `memoriahub:${baseline.id}`, sha256: baseline.sha256 }]);

    const platform = JSON.parse(readFileSync(join(root, 'prisma', 'platform.lock'), 'utf8'));
    expect(platform.rawSqlIndexes).toHaveLength(1 + readInventories(PACKAGE_DIR).rawSqlIndexes.length);
    expect(platform.appMigrations).toEqual(['20270101000000_host_initial', '20270102000000_host_more']);

    const fragments = readdirSync(join(root, 'prisma', 'fragments')).filter((name) => name.startsWith('memoriahub.'));
    expect(fragments).toContain('memoriahub.media.prisma');
    expect(fragments).toContain('memoriahub.ownership.prisma');
    const head = readFileSync(join(root, 'prisma', 'fragments', 'memoriahub.media.prisma'), 'utf8').split('\n');
    expect(head[0]).toBe('// GENERATED by memoriahub-db sync — do not edit');
    expect(head[1]).toBe('// source: @marinoscar/memoriahub-db:schema/memoriahub.media.prisma');
    expect((await checkMemoriahubInstall({ root })).problems).toEqual([]);
  });

  it('is a no-op the second time', async () => {
    const root = historyHost();
    sync(root);
    const lockText = readFileSync(join(root, 'prisma', 'memoriahub.lock'), 'utf8');
    const plan = sync(root);
    expect(plan.installs).toEqual([]);
    expect(plan.memoriahubLockChanged).toBe(false);
    expect(plan.platformLock?.changed).toBe(false);
    expect(plan.fragments.every((f) => f.action === 'unchanged')).toBe(true);
    expect(readFileSync(join(root, 'prisma', 'memoriahub.lock'), 'utf8')).toBe(lockText);
  });

  it('installs a later package migration under its original name and keeps those names', async () => {
    const root = historyHost();
    const { packageDir, id, sql } = packageWithExtra();
    sync(root, { packageDir });
    const plan = sync(root, { packageDir });
    expect(plan.installs).toEqual([]);
    expect(migrationDirs(root)).toContain(id);
    expect(readFileSync(join(root, 'prisma', 'migrations', id, 'migration.sql'), 'utf8')).toBe(sql);
    expect(lockOf(root).migrations.map((m: { installedDir: string | null }) => m.installedDir)).toEqual([null, id]);
    expect(JSON.parse(readFileSync(join(root, 'prisma', 'platform.lock'), 'utf8')).appMigrations).toContain(id);
    expect((await checkMemoriahubInstall({ root, packageDir })).problems).toEqual([]);
  });

  it('check fails on a one-byte change of an installed migration or a fragment, comments included', async () => {
    const root = historyHost();
    const { packageDir, id } = packageWithExtra();
    sync(root, { packageDir });
    const file = join(root, 'prisma', 'migrations', id, 'migration.sql');
    const original = readFileSync(file);
    writeFileSync(file, Buffer.concat([original, Buffer.from('\n')]));
    expect((await checkMemoriahubInstall({ root, packageDir })).problems.map((p) => p.code)).toEqual(['INSTALLED_MODIFIED']);
    writeFileSync(file, original);
    expect((await checkMemoriahubInstall({ root, packageDir })).ok).toBe(true);

    const fragment = join(root, 'prisma', 'fragments', 'memoriahub.media.prisma');
    const text = readFileSync(fragment, 'utf8');
    writeFileSync(fragment, `${text} `);
    expect((await checkMemoriahubInstall({ root, packageDir })).problems.map((p) => p.code)).toEqual(['FRAGMENT_MODIFIED']);
    writeFileSync(fragment, text);

    rmSync(join(root, 'prisma', 'migrations', id), { recursive: true });
    expect((await checkMemoriahubInstall({ root, packageDir })).problems.map((p) => p.code)).toEqual(['LOCK_ENTRY_MISSING']);
  });

  it('check reports a changed baseline, a missing lock, a stale fragment and a platform.lock without the indexes', async () => {
    const root = historyHost();
    sync(root);
    const lock = lockOf(root);
    lock.migrations[0].sha256 = 'f'.repeat(64);
    writeFileSync(join(root, 'prisma', 'memoriahub.lock'), JSON.stringify(lock));
    expect((await checkMemoriahubInstall({ root })).problems.map((p) => p.code)).toContain('LOCK_DIFFERS_FROM_PACKAGE');
    rmSync(join(root, 'prisma', 'memoriahub.lock'));
    writeFileSync(join(root, 'prisma', 'fragments', 'memoriahub.gone.prisma'), '// stale\n');
    writeFileSync(
      join(root, 'prisma', 'platform.lock'),
      readFileSync(join(root, 'prisma', 'platform.lock'), 'utf8').replace(/"rawSqlIndexes": \[[\s\S]*?\n {2}\]/, '"rawSqlIndexes": []'),
    );
    const codes = (await checkMemoriahubInstall({ root })).problems.map((p) => p.code);
    expect(codes).toContain('LOCK_MISSING');
    expect(codes).toContain('FRAGMENT_STALE');
    expect(codes).toContain('PLATFORM_LOCK_INDEX_MISSING');
  });

  it('removes a stale generated fragment on sync', () => {
    const root = historyHost();
    sync(root);
    const stale = join(root, 'prisma', 'fragments', 'memoriahub.gone.prisma');
    writeFileSync(stale, '// stale\n');
    sync(root);
    expect(existsSync(stale)).toBe(false);
  });

  it('refuses a directory that exists under a package id with other bytes', () => {
    const root = historyHost();
    const { packageDir, id } = packageWithExtra();
    mkdirSync(join(root, 'prisma', 'migrations', id), { recursive: true });
    writeFileSync(join(root, 'prisma', 'migrations', id, 'migration.sql'), '-- not the package copy\n');
    expect(() => planMemoriahubSync({ root, packageDir, platformSchemaDir: null })).toThrow(MemoriahubSyncError);
  });
});

describe('sync into a host with no MemoriaHub history', () => {
  it('installs the baseline under a stable name, after the host migrations are dated before it', async () => {
    const root = freshHost();
    const plan = sync(root, { names: 'stable' });
    expect(plan.installs.map((i) => i.action)).toEqual(['copy']);
    const dir = stableName(baseline.id);
    expect(migrationDirs(root)).toContain(dir);
    expect(sha256Hex(readFileSync(join(root, 'prisma', 'migrations', dir, 'migration.sql')))).toBe(baseline.sha256);
    expect(lockOf(root).migrations).toEqual([{ installedDir: dir, originId: `memoriahub:${baseline.id}`, sha256: baseline.sha256 }]);
    expect(JSON.parse(readFileSync(join(root, 'prisma', 'platform.lock'), 'utf8')).appMigrations).toContain(dir);
    expect((await checkMemoriahubInstall({ root })).problems).toEqual([]);
  });

  it('defaults to stable names, and --baseline adopt writes nothing even here', () => {
    expect(planMemoriahubSync({ root: freshHost(), platformSchemaDir: null }).names).toBe('stable');
    const root = freshHost();
    const plan = sync(root, { baseline: 'adopt' });
    expect(plan.installs.map((i) => i.action)).toEqual(['adopt-baseline']);
    expect(migrationDirs(root)).toEqual(['20270101000000_host_initial', '20270102000000_host_more']);
  });

  it('keeps stable names when a package migration is added later', () => {
    const root = freshHost();
    const { packageDir, id } = packageWithExtra();
    const baselineOnly = freshPackage();
    sync(root, { packageDir: baselineOnly });
    const plan = sync(root, { packageDir });
    expect(plan.names).toBe('stable');
    expect(plan.installs.map((i) => i.installedDir)).toEqual([stableName(id)]);
  });

  it('writes nothing on a dry run', () => {
    const root = freshHost();
    const plan = sync(root, { dryRun: true });
    expect(plan.installs).toHaveLength(1);
    expect(migrationDirs(root)).toEqual(['20270101000000_host_initial', '20270102000000_host_more']);
    expect(existsSync(join(root, 'prisma', 'memoriahub.lock'))).toBe(false);
    expect(readdirSync(join(root, 'prisma', 'fragments'))).toEqual(['.gitkeep']);
  });
});

describe('sync refusals', () => {
  it('names the missing host model', () => {
    const root = historyHost();
    const schema = join(root, 'prisma', 'schema', 'platform.host.prisma');
    writeFileSync(schema, readFileSync(schema, 'utf8').replace(/model WorkerNode \{[\s\S]*?\n\}\n/, ''));
    expect(findMissingHostModels(join(root, 'prisma'), null)).toEqual(['WorkerNode']);
    expect(() => planMemoriahubSync({ root, platformSchemaDir: null })).toThrow(/model WorkerNode/);
  });

  it('refuses a platform.lock index listed with another definition', () => {
    const root = historyHost();
    const name = readInventories(PACKAGE_DIR).rawSqlIndexes[0]!.name;
    const file = join(root, 'prisma', 'platform.lock');
    const lock = JSON.parse(readFileSync(file, 'utf8'));
    lock.rawSqlIndexes.push({ name, definition: 'CREATE INDEX other ON public.t USING btree (a)' });
    writeFileSync(file, JSON.stringify(lock, null, 2));
    expect(() => planMemoriahubSync({ root, platformSchemaDir: null })).toThrow(MemoriahubLockError);
    expect(existsSync(join(root, 'prisma', 'memoriahub.lock'))).toBe(false);
  });

  it('refuses a package whose migration differs from the manifest', () => {
    const root = freshHost();
    const packageDir = freshPackage();
    writeFileSync(join(packageDir, 'migrations', baseline.id, 'migration.sql'), '-- edited\n');
    expect(() => planMemoriahubSync({ root, platformSchemaDir: null, packageDir })).toThrow(/sha256 mismatch/);
  });

  it('refuses to re-install a migration the lock says is installed but the folder lost', () => {
    const root = freshHost();
    sync(root);
    rmSync(join(root, 'prisma', 'migrations', stableName(baseline.id)), { recursive: true });
    expect(() => planMemoriahubSync({ root, platformSchemaDir: null })).toThrow(/does not exist/);
  });

  it('refuses a package migration the lock records with another hash', () => {
    const root = historyHost();
    sync(root);
    const lock = lockOf(root);
    lock.migrations[0].sha256 = 'a'.repeat(64);
    writeFileSync(join(root, 'prisma', 'memoriahub.lock'), JSON.stringify(lock));
    expect(() => planMemoriahubSync({ root, platformSchemaDir: null })).toThrow(/never edited/);
  });
});
