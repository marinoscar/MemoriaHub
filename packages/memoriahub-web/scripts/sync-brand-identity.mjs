#!/usr/bin/env node
// =============================================================================
// Sync the brand identity from packages/shared/identity.json
// =============================================================================
//
// A published package cannot import the private `@app/shared` workspace, and the
// rebrand codemod (`scripts/rename.mjs`) rewrites the manifest, not this package.
// `src/brand/identity.ts` is therefore GENERATED from `packages/shared/identity.json`:
// run `npm run brand:sync -w @marinoscar/memoriahub-web` after a rebrand;
// `--check` (and test/brand/identity.test.ts) fails when the file is stale.
//
// Usage: node scripts/sync-brand-identity.mjs [--check]
// Exit: 0 in sync (or written), 1 stale under --check.
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = resolve(PACKAGE_DIR, '..', 'shared', 'identity.json');
const TARGET = resolve(PACKAGE_DIR, 'src', 'brand', 'identity.ts');

/** The generated source for a manifest. */
export function renderIdentity(manifest) {
  const q = (v) => JSON.stringify(String(v));
  return `// GENERATED by scripts/sync-brand-identity.mjs from packages/shared/identity.json.
// Never hand-edit: change the manifest (or run the rebrand codemod) and run
// \`npm run brand:sync -w @marinoscar/memoriahub-web\`.

/**
 * The identity values the brand paints.
 *
 * @stability experimental
 */
export interface MemoriahubBrand {
  /** The product name, shown in the lockup. */
  readonly productName: string;
  /** The one-line tagline. */
  readonly tagline: string;
  /** The brand colour: the mark's plate and the manifest \`theme_color\`. */
  readonly themeColor: string;
  /** The page background an installed app paints before its first frame. */
  readonly backgroundColor: string;
}

/**
 * The identity values of \`packages/shared/identity.json\` that the brand paints.
 *
 * @stability experimental
 */
export const MEMORIAHUB_BRAND: MemoriahubBrand = {
  productName: ${q(manifest.productName)},
  tagline: ${q(manifest.tagline)},
  themeColor: ${q(manifest.themeColor)},
  backgroundColor: ${q(manifest.backgroundColor)},
};
`;
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const next = renderIdentity(manifest);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== next) {
    console.error('src/brand/identity.ts is stale: run `npm run brand:sync -w @marinoscar/memoriahub-web`.');
    process.exit(1);
  }
  console.log('Brand identity is in sync.');
} else {
  writeFileSync(TARGET, next);
  console.log(`Wrote ${TARGET}`);
}
